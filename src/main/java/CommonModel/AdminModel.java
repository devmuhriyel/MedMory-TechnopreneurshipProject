package CommonModel;

public class AdminModel {

    private int id;
    private String name;

    public AdminModel() {}

    public AdminModel(String name) {
        this.name = name;
    }

    public int getId() {
        return id;
    }

    public void setId(int id) {
        this.id = id;
    }

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }
}
